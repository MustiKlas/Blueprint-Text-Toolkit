"""Test için gerçek Unreal metnine benzer Blueprint parçaları üretir."""

TAIL = (",PersistentGuid=00000000000000000000000000000000,bHidden={hidden},"
        "bNotConnectable=False,bDefaultValueIsReadOnly=False,"
        "bDefaultValueIsIgnored=False,bAdvancedView=False,bOrphanedPin=False,)")


def pin(pid, name, cat, sub="", out=False, linked=None, default=None,
        auto=None, friendly=None, hidden=False):
    s = f'   CustomProperties Pin (PinId={pid},PinName="{name}",'
    if friendly:
        s += f'PinFriendlyName=NSLOCTEXT("K2Node", "{friendly}", "{friendly}"),'
    if out:
        s += 'Direction="EGPD_Output",'
    s += (f'PinType.PinCategory="{cat}",PinType.PinSubCategory="{sub}",'
          'PinType.PinSubCategoryObject=None,PinType.ContainerType=None')
    if default is not None:
        s += f',DefaultValue="{default}"'
    if auto is not None:
        s += f',AutogeneratedDefaultValue="{auto}"'
    if linked:
        s += f',LinkedTo=({linked},)'
    return s + TAIL.format(hidden=hidden)


def node(cls, name, extra, pins):
    return (f'Begin Object Class=/Script/BlueprintGraph.{cls} Name="{name}" '
            f'ExportPath="/Script/BlueprintGraph.{cls}\'/Game/BP_Test.BP_Test:Fn.{name}\'"\n'
            + extra + "\n" + "\n".join(pins) + "\nEnd Object\n")


def hexid(prefix, n):
    return f"{prefix}{n:031X}"[:32]
